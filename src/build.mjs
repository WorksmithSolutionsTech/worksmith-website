// Build: node src/build.mjs  →  writes the deployable site into ./site
import { mkdir, writeFile, copyFile, rm, readFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { existsSync } from 'node:fs';
import { build as esbuild } from 'esbuild';
import { site } from './content.mjs';
import { redirects } from './redirects.mjs';
import { layout, redirectStub, render404 } from './templates.mjs';
import { seq, extraPages } from './pages.mjs';
import { FONT_FILES } from './fonts.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ARTIFACT = process.env.EXPLICIT_INDEX === '1';
const out = join(root, ARTIFACT ? '.preview' : 'site');

const relFor = (path) => '../'.repeat(path.split('/').filter(Boolean).length);

const orgLd = `<script type="application/ld+json">${JSON.stringify({
  '@context': 'https://schema.org',
  '@type': 'Organization',
  name: site.legal,
  alternateName: 'Worksmith',
  url: site.domain,
  email: site.email,
  address: { '@type': 'PostalAddress', addressLocality: 'Hyderabad', addressRegion: 'Telangana', addressCountry: 'IN' },
})}</script>`;

async function write(rel, content) {
  const f = join(out, rel);
  await mkdir(dirname(f), { recursive: true });
  await writeFile(f, content);
}

async function main() {
  await rm(out, { recursive: true, force: true });
  await mkdir(out, { recursive: true });

  // pages
  for (const page of seq) {
    const rel = relFor(page.path);
    const html = layout({ rel, page, seq, body: page.render(rel), canonicalPath: page.path, jsonld: page.key === 'home' ? orgLd : '' });
    await write(`${page.path}index.html`, html);
  }
  for (const page of extraPages) {
    const rel = relFor(page.path);
    await write(`${page.path}index.html`, layout({ rel, page, seq, body: page.render(rel), canonicalPath: page.path, prevNext: false, noindex: page.noindex }));
  }

  if (ARTIFACT) {
    // hosted preview: entry page without its own document wrapper (the host adds one)
    const f = join(out, 'index.html');
    let html = await readFile(f, 'utf8');
    const head = html.slice(html.indexOf('<head>') + 6, html.indexOf('</head>'))
      .replace(/<meta charset="utf-8">\n/, '').replace(/<meta name="viewport"[^>]*>\n/, '');
    const body = html.slice(html.indexOf('>', html.indexOf('<body')) + 1, html.indexOf('</body>'));
    await writeFile(f, head.trim() + '\n' + body.trim() + '\n');
  }

  // 404 (served at arbitrary depths → root-absolute asset paths)
  const nf = ARTIFACT ? null : { key: '404', path: '404', label: 'Not found', title: 'Page not found', nav: '', description: 'Page not found.' };
  if (nf) await write('404.html', layout({ rel: '/', page: nf, seq, body: render404('/'), canonicalPath: '', prevNext: false, noindex: true }));

  // assets
  await mkdir(join(out, 'assets/css'), { recursive: true });
  await mkdir(join(out, 'assets/fonts'), { recursive: true });
  await copyFile(join(root, 'src/styles.css'), join(out, 'assets/css/styles.css'));
  await copyFile(join(root, 'src/favicon.svg'), join(out, 'assets/favicon.svg'));
  if (existsSync(join(root, 'src/og.jpg'))) await copyFile(join(root, 'src/og.jpg'), join(out, 'assets/og.jpg'));
  for (const [name, from] of Object.entries(FONT_FILES)) await copyFile(join(root, from), join(out, 'assets/fonts', name));
  await esbuild({
    entryPoints: [join(root, 'src/js/main.js')],
    bundle: true, minify: true, format: 'iife', target: ['es2020'],
    outfile: join(out, 'assets/js/app.js'), legalComments: 'none', logLevel: 'warning',
  });

  if (ARTIFACT) { console.log(`Preview built → ${out}`); return; }

  // ---------- redirects ----------
  const abs = (p) => `${site.domain}${p}`;
  // Netlify
  const netlify = [
    '# Netlify redirects — generated by src/build.mjs. Edit src/redirects.mjs, not this file.',
    '# Canonical host',
    'http://worksmith.tech/*        https://worksmith.tech/:splat      301!',
    'http://www.worksmith.tech/*    https://worksmith.tech/:splat      301!',
    'https://www.worksmith.tech/*   https://worksmith.tech/:splat      301!',
    '',
    ...redirects.flatMap(([from, to, note]) => [note ? `# ${note}` : null, `${from.padEnd(40)} ${to.padEnd(52)} 301!`].filter(Boolean)),
    '',
    '# Everything else that does not exist',
    '/*    /404.html    404',
    '',
  ].join('\n');
  await write('_redirects', netlify);

  // Vercel
  const vercel = {
    $schema: 'https://openapi.vercel.sh/vercel.json',
    cleanUrls: true,
    trailingSlash: true,
    redirects: [
      { source: '/:path*', has: [{ type: 'host', value: 'www.worksmith.tech' }], destination: 'https://worksmith.tech/:path*', permanent: true },
      ...redirects.flatMap(([from, to]) => [
        { source: from, destination: to, permanent: true },
        { source: `${from}/`, destination: to, permanent: true },
      ]),
    ],
  };
  await write('vercel.json', JSON.stringify(vercel, null, 2) + '\n');

  // Apache / cPanel
  const esc = (s) => s.replace(/^\//, '').replace(/[.+()]/g, (c) => `\\${c}`);
  const htaccess = [
    '# Apache / cPanel rules — generated by src/build.mjs. Edit src/redirects.mjs, not this file.',
    'Options -Indexes',
    'DirectoryIndex index.html',
    'ErrorDocument 404 /404.html',
    '',
    '<IfModule mod_rewrite.c>',
    'RewriteEngine On',
    '',
    '# Canonical host: https://worksmith.tech (no www)',
    'RewriteCond %{HTTP_HOST} ^www\\.worksmith\\.tech$ [NC]',
    'RewriteRule ^(.*)$ https://worksmith.tech/$1 [R=301,L]',
    'RewriteCond %{HTTPS} off',
    'RewriteCond %{HTTP:X-Forwarded-Proto} !https',
    'RewriteRule ^(.*)$ https://%{HTTP_HOST}/$1 [R=301,L]',
    '',
    '# Page forwarding',
    ...redirects.flatMap(([from, to, note]) => [note ? `# ${note}` : null, `RewriteRule ^${esc(from)}/?$ ${to} [R=301,L]`].filter(Boolean)),
    '',
    '# Add a trailing slash to page folders',
    'RewriteCond %{REQUEST_FILENAME} !-f',
    'RewriteCond %{REQUEST_FILENAME} -d',
    'RewriteRule ^(.*[^/])$ /$1/ [R=301,L]',
    '</IfModule>',
    '',
    '<IfModule mod_headers.c>',
    '  Header set X-Content-Type-Options "nosniff"',
    '  Header set Referrer-Policy "strict-origin-when-cross-origin"',
    '  <FilesMatch "\\.(woff2|js|css|svg)$">',
    '    Header set Cache-Control "public, max-age=2592000"',
    '  </FilesMatch>',
    '</IfModule>',
    '',
  ].join('\n');
  await write('.htaccess', htaccess);

  // HTML fallbacks: work on any static host (GitHub Pages, S3, plain file servers)
  for (const [from, to, , opts] of redirects) {
    if (opts && opts.stub === false) continue;
    if (/\.html$/.test(from)) continue;
    const depth = from.split('/').filter(Boolean).length;
    const relTo = '../'.repeat(depth) + to.replace(/^\//, '');
    await write(`${from.replace(/^\//, '')}/index.html`, redirectStub({ to: relTo || './', toAbs: abs(to) }));
  }

  // sitemap + robots
  const today = new Date().toISOString().slice(0, 10);
  const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${[...seq, ...extraPages.filter((p) => !p.noindex)].map((p) => `  <url><loc>${site.domain}/${p.path}</loc><lastmod>${today}</lastmod></url>`).join('\n')}
</urlset>
`;
  await write('sitemap.xml', sitemap);
  await write('robots.txt', `User-agent: *\nAllow: /\n\nSitemap: ${site.domain}/sitemap.xml\n`);

  // manifest of the page order, handy for editors
  await write('pages.json', JSON.stringify(seq.map((p, i) => ({ n: i + 1, path: `/${p.path}`, label: p.label })), null, 2) + '\n');

  console.log(`Built ${seq.length} pages + ${extraPages.length} legal + 404, ${redirects.length} redirects → ${out}`);
}

main().catch((e) => { console.error(e); process.exit(1); });
